<?php

declare(strict_types=1);

namespace Ytan\Database;

use PDO;

/**
 * The checked-in base schema (`database/schema.sql`).
 *
 * The first migrations (001-004: poi, route, area, tour, user, ...) were
 * deleted from the repository long ago, so `bin/migrate.php` alone can't
 * build a database from nothing. `generate()` writes the complete current
 * structure of a database as one SQL file - tables, the reference rows the
 * app can't run without (POI types, data sources, the app_settings row) and
 * the list of migrations already contained in it - and `bin/migrate.php`
 * loads that file into an EMPTY database before applying the migrations
 * added since. Regenerate it with `php bin/dump-schema.php`.
 */
final class SchemaDump
{
    /** Lookup tables whose rows are part of the schema (copied completely). */
    public const REFERENCE_TABLES = ['poitype', 'data_source'];

    /**
     * MariaDB 11+ gives tables created without an explicit collation
     * `utf8mb4_uca1400_ai_ci`, which MySQL doesn't know; the rest of the
     * schema uses `utf8mb4_unicode_ci`.
     */
    private const COLLATION_MAP = ['utf8mb4_uca1400_ai_ci' => 'utf8mb4_unicode_ci'];

    public static function generate(PDO $pdo, string $generatedAt): string
    {
        $tables = $pdo->query('SHOW FULL TABLES WHERE Table_type = \'BASE TABLE\'')->fetchAll(PDO::FETCH_COLUMN);
        sort($tables);

        $out = [];
        $out[] = '-- YTAN base schema, generated by bin/dump-schema.php on ' . $generatedAt . '.';
        $out[] = '-- Loaded by bin/migrate.php into an EMPTY database only; do not edit by hand,';
        $out[] = '-- regenerate it (schema changes go into database/migrations/ as usual).';
        $out[] = '';
        $out[] = 'SET NAMES utf8mb4;';
        $out[] = 'SET FOREIGN_KEY_CHECKS=0;';

        foreach ($tables as $table) {
            $create = $pdo->query('SHOW CREATE TABLE `' . $table . '`')->fetch(PDO::FETCH_NUM)[1];
            $out[] = '';
            $out[] = self::normalizeCreate($create) . ';';
        }

        foreach (self::REFERENCE_TABLES as $table) {
            if (!in_array($table, $tables, true)) {
                continue;
            }
            $rows = $pdo->query('SELECT * FROM `' . $table . '` ORDER BY 1')->fetchAll(PDO::FETCH_ASSOC);
            if ($rows !== []) {
                $out[] = '';
                $out[] = self::insertStatement($pdo, $table, $rows);
            }
        }

        if (in_array('app_settings', $tables, true)) {
            // The single settings row with every column at its default -
            // never the source database's own values.
            $out[] = '';
            $out[] = 'INSERT INTO `app_settings` (`id`) VALUES (1);';
        }

        if (in_array('schema_migrations', $tables, true)) {
            $names = $pdo->query('SELECT migration FROM schema_migrations ORDER BY migration')->fetchAll(PDO::FETCH_COLUMN);
            if ($names !== []) {
                $out[] = '';
                $out[] = '-- Migrations already contained in the structure above.';
                $out[] = 'INSERT INTO `schema_migrations` (`migration`, `applied_at`) VALUES';
                $values = array_map(fn ($name) => '(' . $pdo->quote((string) $name) . ', NOW())', $names);
                $out[] = implode(",\n", $values) . ';';
            }
        }

        $out[] = '';
        $out[] = 'SET FOREIGN_KEY_CHECKS=1;';

        return implode("\n", $out) . "\n";
    }

    /** Drops the AUTO_INCREMENT counter and maps MariaDB-only collations. */
    public static function normalizeCreate(string $create): string
    {
        $create = (string) preg_replace('/ AUTO_INCREMENT=\d+/', '', $create);

        return strtr($create, self::COLLATION_MAP);
    }

    /** True when the database has no tables at all. */
    public static function isEmpty(PDO $pdo): bool
    {
        return $pdo->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN) === [];
    }

    /** @param list<array<string, mixed>> $rows */
    private static function insertStatement(PDO $pdo, string $table, array $rows): string
    {
        $columns = array_keys($rows[0]);
        $values = [];
        foreach ($rows as $row) {
            $values[] = '(' . implode(', ', array_map(
                fn ($value) => $value === null ? 'NULL' : $pdo->quote((string) $value),
                array_values($row)
            )) . ')';
        }

        return 'INSERT INTO `' . $table . '` (`' . implode('`, `', $columns) . "`) VALUES\n"
            . implode(",\n", $values) . ';';
    }
}
